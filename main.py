def main():
    # Solicita os números ao usuário
    numero1 = float(input("Digite o primeiro número: "))
    numero2 = float(input("Digite o segundo número: "))
    
    # Calcula a soma
    soma = numero1 + numero2
    
    # Exibe o resultado
    print(f"\n A soma de {numero1} + {numero2} = {soma}")

if __name__ == "__main__":
    main()
